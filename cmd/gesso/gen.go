// gesso gen turns a package's queries.sql into queries.gen.go:
//
//	-- gesso: dialect postgres
//
//	-- name: NoteBySlug :one
//	-- in: slug string
//	-- out: Note
//	SELECT id, slug, title FROM notes WHERE slug = $1;
//
// :one returns out, :many a slice of it, :exec nothing, :execrows the rows
// affected, :execlastid the id the statement inserted — MySQL's answer to
// RETURNING id, which it does not have. out is a struct of the package — every result column must name one of
// its fields, by a db:"col" tag or by snake_case — or, for one column, any type.
// in lists the parameters as Go names and types: for PostgreSQL in the order of
// $1, $2…; for SQLite and MySQL, whose ? are positional, in the order they appear
// in the SQL.
//
// What is checked when generating: the dialect is declared; the placeholders
// match in; every column names a field, and no two the same one. What is not:
// column types and nullability — a NULL scanned into a string fails at run time;
// give a nullable column a pointer or sql.Null field.

const genHeader = "// Code generated by gesso gen from queries.sql. DO NOT EDIT."

type query struct {
	line    int
	name    string
	kind    string // one, many, exec, execrows, execlastid
	params  []param
	out     string
	sql     string
	columns []string
}

type param struct{ name, typ string }

var (
	nameLine    = regexp.MustCompile(`^--\s*name:\s*([A-Za-z_][A-Za-z0-9_]*)\s+:(one|many|exec|execrows|execlastid)\s*$`)
	dialectLine = regexp.MustCompile(`^--\s*gesso:\s*dialect\s+(\w+)\s*$`)
	reserved    = []string{"ctx", "q", "out", "rows", "err", "item", "res"}
)

func gen(args []string, dir string, stdout io.Writer, now func() time.Time) (stale int, err error) {
	flags := newFlags("gen")
	checkOnly := flags.Bool("check", false, "report stale or missing generated files instead of writing them")
	drop := flags.Bool("drop", false, "let a field gone from a model drop its column, and its data")
	noMigration := flags.Bool("no-migration", false, "write no migration for a model's change: you wrote it yourself")
	pos, err := parseFlags(flags, args)
	if err != nil {
		return 0, err
	}
	roots := pos
	if len(roots) == 0 {
		roots = []string{"."}
	}
	var files, modelDirs []string
	for _, root := range roots {
		root = filepath.Join(dir, strings.TrimSuffix(root, "/..."))
		err := filepath.WalkDir(root, func(p string, d fs.DirEntry, err error) error {
			if err != nil {
				return err
			}
			if d.IsDir() && p != root && (strings.HasPrefix(d.Name(), ".") || d.Name() == "testdata" || d.Name() == "vendor") {
				return filepath.SkipDir
			}
			if !d.IsDir() && d.Name() == "queries.sql" {
				files = append(files, p)
			}
			if d.IsDir() && d.Name() == "models" {
				modelDirs = append(modelDirs, p)
			}
			return nil
		})
		if err != nil {
			return 0, err
		}
	}
	var errs []error
	models := 0
	for _, md := range modelDirs {
		paths, err := genModel(md, genModelOptions{root: dir, dialect: projectDialect(dir), check: *checkOnly, drop: *drop, noMigration: *noMigration, now: now})
		if errors.Is(err, errNoModel) {
			continue
		}
		models++
		for _, p := range paths {
			rel, _ := filepath.Rel(dir, p)
			if *checkOnly {
				fmt.Fprintln(stdout, "stale", rel)
				stale++
			} else {
				fmt.Fprintln(stdout, "generated", rel)
			}
		}
		if err != nil {
			errs = append(errs, err)
		}
	}
	if len(files) == 0 && models == 0 {
		return 0, errors.New("no queries.sql or //gesso:table model found")
	}
	slices.Sort(files)
	for _, f := range files {
		src, err := generate(f)
		if err != nil {
			errs = append(errs, err)
			continue
		}
		target := filepath.Join(filepath.Dir(f), "queries.gen.go")
		rel, _ := filepath.Rel(dir, target)
		if *checkOnly {
			if cur, err := os.ReadFile(target); err != nil || !bytes.Equal(cur, src) {
				fmt.Fprintln(stdout, "stale", rel)
				stale++
			}
			continue
		}
		if err := os.WriteFile(target, src, 0o644); err != nil {
			errs = append(errs, err)
			continue
		}
		fmt.Fprintln(stdout, "generated", rel)
	}
	return stale, errors.Join(errs...)
}

func generate(file string) ([]byte, error) {
	data, err := os.ReadFile(file)
	if err != nil {
		return nil, err
	}
	dialect, queries, err := parseQueries(file, string(data))
	if err != nil {
		return nil, err
	}
	pkg, err := loadForGen(filepath.Dir(file))
	if err != nil {
		return nil, fmt.Errorf("%s: %w", file, err)
	}
	var body bytes.Buffer
	imports := map[string]bool{"context": true, "github.com/Elagoht/gesso/db": true}
	for _, q := range queries {
		at := fmt.Sprintf("%s:%d", file, q.line)
		toks, err := scanSQL(q.sql, dialect)
		if err != nil {
			return nil, fmt.Errorf("%s: %s: %w", at, q.name, err)
		}
		n, err := placeholders(toks, dialect)
		if err != nil {
			return nil, fmt.Errorf("%s: %s: %w", at, q.name, err)
		}
		if n != len(q.params) {
			return nil, fmt.Errorf("%s: %s: the SQL takes %d parameters, in: lists %d", at, q.name, n, len(q.params))
		}
		for _, p := range q.params {
			for _, imp := range typeImports(p.typ) {
				if imp == "" {
					return nil, fmt.Errorf("%s: %s: parameter %s: type %q: only time, sql and json are imported for you", at, q.name, p.name, p.typ)
				}
				imports[imp] = true
			}
		}
		var scan []string
		if q.kind == "one" || q.kind == "many" {
			if q.out == "" {
				return nil, fmt.Errorf("%s: %s: a :%s query needs an out: line", at, q.name, q.kind)
			}
			q.columns, err = resultColumns(toks)
			if err != nil {
				return nil, fmt.Errorf("%s: %s: %w", at, q.name, err)
			}
			scan, err = scanTargets(pkg, q)
			if err != nil {
				return nil, fmt.Errorf("%s: %s: %w", at, q.name, err)
			}
			for _, imp := range typeImports(q.out) {
				if imp != "" {
					imports[imp] = true
				}
			}
		}
		writeQuery(&body, q, scan, filepath.Base(file))
	}
	var src bytes.Buffer
	fmt.Fprintf(&src, "%s\n\npackage %s\n\nimport (\n", genHeader, pkg.Name())
	for _, imp := range slices.Sorted(func(yield func(string) bool) {
		for k := range imports {
			if !yield(k) {
				return
			}
		}
	}) {
		fmt.Fprintf(&src, "\t%q\n", imp)
	}
	src.WriteString(")\n\n// Queries runs the queries of queries.sql on a db.DB: the pool, or a transaction.\ntype Queries struct {\n\tdb db.DB\n}\n\n")
	src.WriteString("// NewQueries runs on d.\nfunc NewQueries(d db.DB) *Queries { return &Queries{db: d} }\n")
	src.Write(body.Bytes())
	out, err := format.Source(src.Bytes())
	if err != nil {
		return nil, fmt.Errorf("%s: the generated code does not format: %w\n%s", file, err, src.String())
	}
	return out, nil
}

func parseQueries(file, text string) (string, []query, error) {
	lines := strings.Split(text, "\n")
	dialect := ""
	var queries []query
	var cur *query
	for i, raw := range lines {
		line := strings.TrimSpace(raw)
		at := fmt.Sprintf("%s:%d", file, i+1)
		if m := dialectLine.FindStringSubmatch(line); m != nil {
			dialect = m[1]
			if dialect != "postgres" && dialect != "sqlite" && dialect != "mysql" {
				return "", nil, fmt.Errorf("%s: unknown dialect %q: postgres, sqlite or mysql", at, dialect)
			}
			continue
		}
		if m := nameLine.FindStringSubmatch(line); m != nil {
			if cur != nil {
				queries = append(queries, *cur)
			}
			cur = &query{line: i + 1, name: m[1], kind: m[2]}
			if !ast.IsExported(cur.name) {
				return "", nil, fmt.Errorf("%s: %s: a query's name is exported: begin it with a capital", at, cur.name)
			}
			continue
		}
		if cur == nil {
			if line != "" && !strings.HasPrefix(line, "--") {
				return "", nil, fmt.Errorf("%s: SQL before the first -- name: line", at)
			}
			continue
		}
		if rest, ok := strings.CutPrefix(line, "-- in:"); ok && cur.sql == "" {
			for part := range strings.SplitSeq(rest, ",") {
				fields := strings.Fields(part)
				if len(fields) != 2 || !isIdent(fields[0]) {
					return "", nil, fmt.Errorf("%s: an in: parameter is name type, got %q", at, strings.TrimSpace(part))
				}
				if slices.Contains(reserved, fields[0]) {
					return "", nil, fmt.Errorf("%s: parameter %q: the generated code uses that name", at, fields[0])
				}
				if _, err := parser.ParseExpr(fields[1]); err != nil {
					return "", nil, fmt.Errorf("%s: parameter %s: %q is not a Go type", at, fields[0], fields[1])
				}
				cur.params = append(cur.params, param{fields[0], fields[1]})
			}
			continue
		}
		if rest, ok := strings.CutPrefix(line, "-- out:"); ok && cur.sql == "" {
			cur.out = strings.TrimSpace(rest)
			if _, err := parser.ParseExpr(cur.out); err != nil {
				return "", nil, fmt.Errorf("%s: out: %q is not a Go type", at, cur.out)
			}
			continue
		}
		if cur.sql == "" && (line == "" || strings.HasPrefix(line, "--")) {
			continue
		}
		cur.sql += raw + "\n"
	}
	if cur != nil {
		queries = append(queries, *cur)
	}
	if dialect == "" {
		return "", nil, fmt.Errorf("%s: declare the dialect first: -- gesso: dialect postgres (or sqlite, mysql)", file)
	}
	seen := map[string]int{}
	for i := range queries {
		q := &queries[i]
		q.sql = strings.TrimRight(strings.TrimSpace(q.sql), ";")
		if q.sql == "" {
			return "", nil, fmt.Errorf("%s:%d: %s has no SQL", file, q.line, q.name)
		}
		if prev, ok := seen[q.name]; ok {
			return "", nil, fmt.Errorf("%s:%d: %s is also at line %d", file, q.line, q.name, prev)
		}
		seen[q.name] = q.line
	}
	return dialect, queries, nil
}

func isIdent(s string) bool {
	if s == "" {
		return false
	}
	for i, r := range s {
		if !(unicode.IsLetter(r) || r == '_' || (i > 0 && unicode.IsDigit(r))) {
			return false
		}
	}
	return true
}

var qualifier = regexp.MustCompile(`([A-Za-z_][A-Za-z0-9_]*)\.`)

// typeImports are the imports a type expression needs: "" for a package gen does
// not know.
func typeImports(typ string) []string {
	known := map[string]string{"time": "time", "sql": "database/sql", "json": "encoding/json"}
	var out []string
	for _, m := range qualifier.FindAllStringSubmatch(typ, -1) {
		out = append(out, known[m[1]])
	}
	return out
}

// loadForGen type-checks the package with its generated file blanked: the
// handwritten code may use Queries, which a missing or stale file would break.
// Errors elsewhere are tolerated; only the out types must resolve.
func loadForGen(dir string) (*types.Package, error) {
	abs, err := filepath.Abs(dir)
	if err != nil {
		return nil, err
	}
	pkgName, err := packageName(abs)
	if err != nil {
		return nil, err
	}
	pkgs, err := packages.Load(&packages.Config{
		Mode:    packages.NeedName | packages.NeedTypes | packages.NeedSyntax | packages.NeedTypesInfo,
		Dir:     abs,
		Overlay: map[string][]byte{filepath.Join(abs, "queries.gen.go"): []byte("package " + pkgName + "\n")},
	}, ".")
	if err != nil {
		return nil, err
	}
	if len(pkgs) != 1 || pkgs[0].Types == nil {
		return nil, errors.New("the package does not load")
	}
	return pkgs[0].Types, nil
}

// packageName reads the package clause of a handwritten Go file in dir.
func packageName(dir string) (string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return "", err
	}
	for _, e := range entries {
		n := e.Name()
		if strings.HasSuffix(n, ".go") && !strings.HasSuffix(n, "_test.go") && n != "queries.gen.go" {
			f, err := parser.ParseFile(gotoken.NewFileSet(), filepath.Join(dir, n), nil, parser.PackageClauseOnly)
			if err == nil {
				return f.Name.Name, nil
			}
		}
	}
	return "", errors.New("no Go file beside queries.sql names the package")
}

// scanTargets maps the result columns onto out: its fields for a struct, out
// itself for one column of another type.
func scanTargets(pkg *types.Package, q query) ([]string, error) {
	var st *types.Struct
	if obj := pkg.Scope().Lookup(q.out); obj != nil {
		if tn, ok := obj.(*types.TypeName); ok {
			st, _ = tn.Type().Underlying().(*types.Struct)
		}
	}
	if st == nil || q.out == "time.Time" {
		if len(q.columns) != 1 {
			return nil, fmt.Errorf("out: %s is not a struct of package %s, and the query returns %d columns", q.out, pkg.Name(), len(q.columns))
		}
		return []string{"&out"}, nil
	}
	byColumn := map[string]string{}
	var walk func(st *types.Struct, prefix string)
	walk = func(st *types.Struct, prefix string) {
		for i := range st.NumFields() {
			f := st.Field(i)
			tag := reflect.StructTag(st.Tag(i)).Get("db")
			if f.Embedded() && tag == "" {
				if inner, ok := f.Type().Underlying().(*types.Struct); ok {
					walk(inner, prefix+f.Name()+".")
					continue
				}
			}
			if !f.Exported() || tag == "-" {
				continue
			}
			col := tag
			if col == "" {
				col = snake(f.Name())
			}
			if _, dup := byColumn[col]; !dup {
				byColumn[col] = prefix + f.Name()
			}
		}
	}
	walk(st, "")
	var targets []string
	used := map[string]string{}
	for _, col := range q.columns {
		field, ok := byColumn[col]
		if !ok {
			return nil, fmt.Errorf("column %q has no field in %s: add one, tag one db:%q, or alias the column", col, q.out, col)
		}
		if other, ok := used[field]; ok {
			return nil, fmt.Errorf("columns %q and %q both land in %s.%s", other, col, q.out, field)
		}
		used[field] = col
		targets = append(targets, "&out."+field)
	}
	return targets, nil
}

// snake is a Go name in snake_case, initialisms kept whole: UserID is user_id,
// HTTPServer is http_server.
func snake(name string) string {
	r := []rune(name)
	var b strings.Builder
	for i, c := range r {
		if unicode.IsUpper(c) && i > 0 {
			prevLower := unicode.IsLower(r[i-1]) || unicode.IsDigit(r[i-1])
			nextLower := i+1 < len(r) && unicode.IsLower(r[i+1])
			if prevLower || (unicode.IsUpper(r[i-1]) && nextLower) {
				b.WriteByte('_')
			}
		}
		b.WriteRune(unicode.ToLower(c))
	}
	return b.String()
}

func writeQuery(b *bytes.Buffer, q query, scan []string, file string) {
	constName := strings.ToLower(q.name[:1]) + q.name[1:] + "SQL"
	fmt.Fprintf(b, "\nconst %s = %s\n\n", constName, strconv.Quote(q.sql))
	var params, args []string
	for _, p := range q.params {
		params = append(params, p.name+" "+p.typ)
		args = append(args, p.name)
	}
	sig := strings.Join(append([]string{"ctx context.Context"}, params...), ", ")
	call := strings.Join(append([]string{"ctx", constName}, args...), ", ")
	fmt.Fprintf(b, "// %s runs the query at %s:%d.\n", q.name, file, q.line)
	switch q.kind {
	case "one":
		fmt.Fprintf(b, "func (q *Queries) %s(%s) (%s, error) {\n\tvar out %s\n\terr := q.db.QueryRowContext(%s).Scan(%s)\n\treturn out, err\n}\n",
			q.name, sig, q.out, q.out, call, strings.Join(scan, ", "))
	case "many":
		item := strings.ReplaceAll(strings.Join(scan, ", "), "&out", "&item")
		fmt.Fprintf(b, `func (q *Queries) %s(%s) ([]%s, error) {
	rows, err := q.db.QueryContext(%s)
	if err != nil {
		return nil, err
	}
	defer rows.Close()
	out := []%s{}
	for rows.Next() {
		var item %s
		if err := rows.Scan(%s); err != nil {
			return nil, err
		}
		out = append(out, item)
	}
	return out, rows.Err()
}
`, q.name, sig, q.out, call, q.out, q.out, item)
	case "exec":
		fmt.Fprintf(b, "func (q *Queries) %s(%s) error {\n\t_, err := q.db.ExecContext(%s)\n\treturn err\n}\n", q.name, sig, call)
	case "execrows", "execlastid":
		result := "RowsAffected"
		if q.kind == "execlastid" {
			result = "LastInsertId"
		}
		fmt.Fprintf(b, "func (q *Queries) %s(%s) (int64, error) {\n\tres, err := q.db.ExecContext(%s)\n\tif err != nil {\n\t\treturn 0, err\n\t}\n\treturn res.%s()\n}\n", q.name, sig, call, result)
	}
}
