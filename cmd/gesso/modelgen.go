// parseModel reads the //gesso:table struct in the models folder dir.
func parseModel(dir string) (*model, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	fset := gotoken.NewFileSet()
	var found *model
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, ".gen.go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(dir, name), nil, parser.ParseComments)
		if err != nil {
			return nil, err
		}
		for _, d := range f.Decls {
			g, ok := d.(*ast.GenDecl)
			if !ok || g.Tok != gotoken.TYPE || g.Doc == nil {
				continue
			}
			table := ""
			var directives [][]string
			for _, c := range g.Doc.List {
				if m := tableDirective.FindStringSubmatch(c.Text); m != nil {
					table = m[1]
				} else if m := modelDirective.FindStringSubmatch(c.Text); m != nil {
					directives = append(directives, m)
				} else if strings.HasPrefix(c.Text, "//gesso:") {
					return nil, fmt.Errorf("%s: unknown %s: //gesso:table <name>, //gesso:sortable, //gesso:auth, //gesso:write <guard>, //gesso:read <guard>", dir, c.Text)
				}
			}
			if table == "" {
				continue
			}
			if found != nil {
				return nil, fmt.Errorf("%s: two //gesso:table structs; a module has one", dir)
			}
			ts := g.Specs[0].(*ast.TypeSpec)
			st, ok := ts.Type.(*ast.StructType)
			if !ok {
				return nil, fmt.Errorf("%s: %s is not a struct", dir, ts.Name.Name)
			}
			if found, err = modelOf(fset, ts.Name.Name, table, st); err != nil {
				return nil, fmt.Errorf("%s: %w", dir, err)
			}
			for _, d := range directives {
				if err := found.direct(d[1], d[2]); err != nil {
					return nil, fmt.Errorf("%s: %w", dir, err)
				}
			}
			if err := found.check(); err != nil {
				return nil, fmt.Errorf("%s: %w", dir, err)
			}
		}
	}
	if found == nil {
		return nil, errNoModel
	}
	found.Pkg = filepath.Base(filepath.Dir(dir))
	return found, nil
}

var errNoModel = errors.New("no //gesso:table struct")

// transforms are the options that change a string after it is checked.
var transforms = map[string]bool{"trim": true, "lower": true, "upper": true, "collapse": true, "slugify": true}

// imageTypes are the images an image field takes: rasters, never SVG, whose
// scripts would run where it is shown.
var imageTypes = []string{"image/png", "image/jpeg", "image/gif", "image/webp"}

// checkFile is what holds for a file or an image field.
func (f *mfield) checkFile() error {
	if f.Key || f.Unique || f.Index || f.Sort || f.Filterable || f.Orderable || f.Default != "" || f.GateGuard != "" || len(f.Transforms) > 0 || len(f.Rules) > 0 || f.Base == "text" {
		return fmt.Errorf("a %s is uploaded on its own route: it takes accept, maxsize, public, routes, listable, guard, self, optional and, an image, fit, fill, format, quality", f.File)
	}
	if f.File == "file" && (f.Width != 0 || f.Format != "" || f.Quality != 0) {
		return errors.New("fit, fill, format and quality are for an image")
	}
	if f.File == "image" {
		if len(f.Accept) == 0 {
			f.Accept = imageTypes
		}
		for _, a := range f.Accept {
			if !slices.Contains(imageTypes, a) {
				return fmt.Errorf("an image takes %s, not %s", strings.Join(imageTypes, ", "), a)
			}
		}
	}
	if f.MaxBytes == 0 {
		f.MaxSize, f.MaxBytes = "10MiB", 10<<20
	}
	f.Base, f.Optional = "file", true
	return nil
}

// parseSize reads 512KB, 5MiB, 1GB.
func parseSize(s string) (int64, error) {
	units := []struct {
		suffix string
		n      int64
	}{{"KiB", 1 << 10}, {"MiB", 1 << 20}, {"GiB", 1 << 30}, {"KB", 1e3}, {"MB", 1e6}, {"GB", 1e9}, {"B", 1}}
	for _, u := range units {
		if num, ok := strings.CutSuffix(s, u.suffix); ok {
			v, err := strconv.ParseInt(num, 10, 64)
			if err != nil || v <= 0 {
				break
			}
			return v * u.n, nil
		}
	}
	return 0, fmt.Errorf("maxsize %q: a number and B, KB, KiB, MB, MiB, GB or GiB", s)
}

// direct applies a directive: //gesso:sortable, //gesso:write <guard>,
// //gesso:read <guard>.
func (m *model) direct(name, arg string) error {
	switch name {
	case "sortable", "auth":
		if arg != "" {
			return fmt.Errorf("//gesso:%s takes nothing", name)
		}
		m.Sortable = m.Sortable || name == "sortable"
		m.Auth = m.Auth || name == "auth"
	case "write", "read":
		if arg == "" {
			return fmt.Errorf("//gesso:%s takes a guard: //gesso:%s signedIn", name, name)
		}
		if name == "write" {
			m.Write = exported(arg)
		} else {
			m.Read = exported(arg)
		}
		m.guardFiles = append(m.guardFiles, arg)
	}
	return nil
}

// check is what holds across fields.
func (m *model) check() error {
	if m.Sortable && m.Sort != nil {
		return fmt.Errorf("%s is //gesso:sortable, kept in the client's order: %s cannot sort it too", m.Entity, m.Sort.Go)
	}
	seen := map[string]bool{}
	for i := range m.Fields {
		f := &m.Fields[i]
		if f.Column == "position" && m.Sortable {
			return fmt.Errorf("%s.%s: a sortable model keeps its order in a column named position", m.Entity, f.Go)
		}
		if f.GateGuard != "" {
			if m.Gate != nil {
				return fmt.Errorf("%s: two gates", m.Entity)
			}
			m.Gate = f
			m.guardFiles = append(m.guardFiles, unexported(f.GateGuard))
		}
		if f.Guard != "" {
			m.guardFiles = append(m.guardFiles, unexported(f.Guard))
			if !seen[f.Guard] {
				seen[f.Guard] = true
				m.Guarded = append(m.Guarded, f.Guard)
			}
		}
		m.Listable = m.Listable || f.Listable
	}
	if err := m.checkAuth(); err != nil {
		return err
	}
	return nil
}

// checkAuth is what holds for the users of //gesso:auth, and for self.
func (m *model) checkAuth() error {
	for _, f := range m.Fields {
		if f.Self && !m.Auth {
			return fmt.Errorf("%s.%s: self is for the users of a //gesso:auth model", m.Entity, f.Go)
		}
		if f.Self && f.Guard != "" {
			return fmt.Errorf("%s.%s: a field users change on themselves has no guard", m.Entity, f.Go)
		}
	}
	if !m.Auth {
		return nil
	}
	if m.Key == nil || m.Key.Column != "username" || m.Key.Base != "string" {
		return fmt.Errorf("%s is //gesso:auth: its key is Username string `gesso:\"key,…\"`, what users sign in with", m.Entity)
	}
	if m.Gate != nil || m.Sortable {
		return fmt.Errorf("%s is //gesso:auth: it takes no gate and is not sortable", m.Entity)
	}
	for _, f := range m.Fields {
		switch f.Column {
		case "password_hash", "roles", "created_at":
			return fmt.Errorf("%s.%s: %s is a column //gesso:auth keeps itself", m.Entity, f.Go, f.Column)
		}
		if f.Unique && !f.Key {
			return fmt.Errorf("%s.%s: a user made from the command line leaves it empty, so it cannot be unique", m.Entity, f.Go)
		}
	}
	return nil
}

func unexported(name string) string { return strings.ToLower(name[:1]) + name[1:] }

func modelOf(fset *gotoken.FileSet, entity, table string, st *ast.StructType) (*model, error) {
	m := &model{Entity: entity, Table: table, Plural: camel(table)}
	if m.Plural == m.Entity {
		m.Plural += "List"
	}
	for i, fl := range st.Fields.List {
		if len(fl.Names) != 1 {
			return nil, fmt.Errorf("%s: one name per field", entity)
		}
		var typ bytes.Buffer
		_ = format.Node(&typ, fset, fl.Type)
		name := fl.Names[0].Name
		if i == 0 {
			if name != "ID" || typ.String() != "int64" {
				return nil, fmt.Errorf("%s: the first field is ID int64", entity)
			}
			continue
		}
		var tag string
		if fl.Tag != nil {
			raw, _ := strconv.Unquote(fl.Tag.Value)
			tag = reflect.StructTag(raw).Get("gesso")
		}
		f, err := newMField(name, typ.String(), tag)
		if err != nil {
			return nil, fmt.Errorf("%s.%s: %w", entity, name, err)
		}
		m.Fields = append(m.Fields, f)
	}
	if len(m.Fields) == 0 {
		return nil, fmt.Errorf("%s has no fields beside ID", entity)
	}
	for i := range m.Fields {
		f := &m.Fields[i]
		if f.Key {
			if m.Key != nil {
				return nil, fmt.Errorf("%s: two key fields", entity)
			}
			m.Key = f
		}
		if f.Sort {
			if m.Sort != nil {
				return nil, fmt.Errorf("%s: two sort fields", entity)
			}
			m.Sort = f
		}
		m.UsesTime = m.UsesTime || f.Base == "time"
		m.UsesDate = m.UsesDate || f.Base == "date"
	}
	return m, nil
}

func newMField(name, typ, tag string) (mfield, error) {
	col := snake(name)
	f := mfield{Go: name, JSON: lowerCamel(col), Column: col, Type: typ}
	if name == "Key" {
		return f, errors.New("a field named Key would clash with the requests' path parameter: call it something else")
	}
	base, ok := baseOf[strings.TrimPrefix(typ, "*")]
	if !ok {
		return f, fmt.Errorf("type %s: a field is string, int64, bool, float64, time.Time or date.Date, or a pointer to one, for a column that takes NULL", typ)
	}
	f.Base, f.Nullable = base, strings.HasPrefix(typ, "*")
	maxGiven := false
	for opt := range strings.SplitSeq(tag, ",") {
		opt = strings.TrimSpace(opt)
		if opt == "" {
			continue
		}
		rule, value, _ := strings.Cut(opt, "=")
		switch {
		case opt == "file" || opt == "image":
			if typ != "string" {
				return f, fmt.Errorf("%s is a string: the stored file's key", opt)
			}
			f.File = opt
		case rule == "accept":
			f.Accept = strings.Fields(value)
		case rule == "maxsize":
			n, err := parseSize(value)
			if err != nil {
				return f, err
			}
			f.MaxSize, f.MaxBytes = value, n
		case rule == "fit" || rule == "fill":
			if _, err := fmt.Sscanf(value, "%dx%d", &f.Width, &f.Height); err != nil || f.Width <= 0 || f.Height <= 0 {
				return f, fmt.Errorf("%s is WIDTHxHEIGHT: %s=1600x900", rule, rule)
			}
			f.Fill = rule == "fill"
		case rule == "format":
			if value != "jpeg" && value != "png" {
				return f, errors.New("format is jpeg or png")
			}
			f.Format = value
		case rule == "quality":
			if _, err := fmt.Sscanf(value, "%d", &f.Quality); err != nil || f.Quality < 1 || f.Quality > 100 {
				return f, errors.New("quality is 1 to 100")
			}
		case transforms[opt]:
			f.Transforms = append(f.Transforms, opt)
		case opt == "self":
			f.Self = true
		case opt == "public":
			f.Public = true
		case opt == "routes":
			f.Routes = true
		case opt == "listable":
			f.Listable = true
		case opt == "filterable":
			f.Filterable = true
		case opt == "orderable":
			f.Orderable = true
		case rule == "default":
			if value == "" {
				return f, errors.New("default takes a value: default=draft, default=@today, default=@now, default=@user")
			}
			f.Default = value
		case rule == "guard" || rule == "gate":
			if !guardName.MatchString(value) {
				return f, fmt.Errorf("%s names a guard: %s=signedIn", rule, rule)
			}
			if rule == "guard" {
				f.Guard = exported(value)
			} else {
				f.GateGuard = exported(value)
			}
		case opt == "text":
			if base != "string" {
				return f, errors.New("text is for a string")
			}
			f.Base = "text"
		case opt == "key":
			f.Key, f.Unique = true, true
		case opt == "unique":
			f.Unique = true
		case opt == "index":
			f.Index = true
		case opt == "optional":
			f.Optional = true
		case opt == "sort":
			f.Sort = true
		case ruleNames[rule]:
			f.Rules = append(f.Rules, opt)
			maxGiven = maxGiven || rule == "max"
		case options[rule]:
			return f, fmt.Errorf("%q takes no value", rule)
		default:
			return f, fmt.Errorf("unknown option or rule %q: options are key, unique, index, optional, sort, text, listable, filterable, orderable, default=<value>, guard=<guard>, gate=<guard>, file, image, accept=, maxsize=, fit=, fill=, format=, quality=, trim, lower, upper, collapse, slugify, self; rules are validate's (max=200, email, slug, oneof=a b …)", opt)
		}
	}
	if f.File != "" {
		if err := f.checkFile(); err != nil {
			return f, err
		}
		return f, nil
	}
	if f.Accept != nil || f.MaxSize != "" || f.Width != 0 || f.Format != "" || f.Quality != 0 || f.Public || f.Routes {
		return f, errors.New("accept, maxsize, public, routes, fit, fill, format and quality are for a file or an image")
	}
	if len(f.Transforms) > 0 && base != "string" {
		return f, fmt.Errorf("%s is for a string", f.Transforms[0])
	}
	if f.GateGuard != "" && (base != "bool" || f.Nullable) {
		return f, errors.New("a gate is a bool: true opens the record to everyone")
	}
	if f.Guard != "" && (f.Key || f.Filterable || f.Orderable || f.Sort || f.GateGuard != "") {
		return f, errors.New("a guarded field is not the key, a filter, an order or a gate: they would show it to everyone")
	}
	if f.Guard != "" {
		f.Optional = true // whoever may not write it leaves it out
	}
	if f.Orderable && (f.Nullable || f.Base == "text" || f.Base == "bool") {
		return f, errors.New("orderable is for a string, number, time or date that is never NULL")
	}
	if f.Filterable && f.Base == "text" {
		return f, errors.New("a text column is not filterable: drop text, and give it a max")
	}
	if f.Default != "" {
		if err := f.checkDefault(); err != nil {
			return f, err
		}
		f.Optional = true // left out, it takes the default
	}
	if f.Optional && !f.Nullable && f.Default == "" && (base == "time" || base == "date") {
		// Left out, it would be year 1, which MySQL refuses and nobody means.
		return f, fmt.Errorf("an optional %s is a pointer, *%s, NULL when left out", base, strings.TrimPrefix(typ, "*"))
	}
	if f.Nullable && !f.Optional {
		f.Optional = true // a pointer may be left out
	}
	if f.Key && (f.Optional || (f.Base != "string" && f.Base != "int")) {
		return f, errors.New("a key is a string or an int64 that is always given")
	}
	if (f.Unique || f.Index) && f.Base == "text" {
		return f, errors.New("a text column is not unique or indexed: MySQL cannot index TEXT; drop text, and give it a max")
	}
	if f.Sort && (f.Nullable || f.Base == "text" || f.Base == "bool") {
		return f, errors.New("sort is for a string, number, time or date that is never NULL")
	}
	if f.Base == "string" && !maxGiven {
		f.Rules = append([]string{"max=255"}, f.Rules...)
	}
	rules := slices.Clone(f.Rules)
	if !f.Optional && (f.Base == "string" || f.Base == "text" || f.Base == "time" || f.Base == "date") {
		rules = append([]string{"required"}, rules...)
	}
	f.Rule = strings.Join(rules, ",")
	patch := slices.Clone(f.Rules)
	if !f.Nullable {
		patch = append([]string{"notnull"}, patch...)
	}
	f.Patch = strings.Join(patch, ",")
	return f, nil
}

// varcharLen is the MySQL VARCHAR length of a string field: its max, or 255.
func (f mfield) varcharLen() int {
	for _, r := range f.Rules {
		if v, ok := strings.CutPrefix(r, "max="); ok {
			if n, err := strconv.Atoi(v); err == nil && n > 0 && n <= 16383 {
				return n
			}
		}
	}
	return 255
}

// column is the schema gen remembers of a field, and diffs against.
type column struct {
	Name     string `json:"name"`
	SQL      string `json:"sql"` // the type, without NULL-ness
	Base     string `json:"base"`
	Nullable bool   `json:"nullable,omitempty"`
	Unique   bool   `json:"unique,omitempty"`
	Index    bool   `json:"index,omitempty"`
}

type schemaSnapshot struct {
	Table   string   `json:"table"`
	Dialect string   `json:"dialect"`
	Auth    bool     `json:"auth,omitempty"` // every column but the key has a default: users add fills only its own
	Columns []column `json:"columns"`
}

func sqlType(f mfield, dialect string) string {
	switch f.Base {
	case "file":
		if dialect == "mysql" {
			return "VARCHAR(255)"
		}
		return "TEXT"
	case "string":
		if dialect == "mysql" {
			return "VARCHAR(" + strconv.Itoa(f.varcharLen()) + ")"
		}
		return "TEXT"
	case "text":
		return "TEXT"
	case "int":
		if dialect == "sqlite" {
			return "INTEGER"
		}
		return "BIGINT"
	case "bool":
		return "BOOLEAN"
	case "float":
		return map[string]string{"postgres": "DOUBLE PRECISION", "sqlite": "REAL", "mysql": "DOUBLE"}[dialect]
	case "time":
		return map[string]string{"postgres": "TIMESTAMPTZ", "sqlite": "TIMESTAMP", "mysql": "DATETIME(6)"}[dialect]
	}
	return "DATE"
}

func (m model) snapshot() schemaSnapshot {
	s := schemaSnapshot{Table: m.Table, Dialect: m.Dialect, Columns: []column{}}
	for _, f := range m.Fields {
		s.Columns = append(s.Columns, column{Name: f.Column, SQL: sqlType(f, m.Dialect), Base: f.Base, Nullable: f.Nullable, Unique: f.Unique, Index: f.Index})
	}
	if m.Sortable {
		s.Columns = append(s.Columns, column{Name: "position", SQL: sqlType(mfield{Base: "int"}, m.Dialect), Base: "int", Index: true})
	}
	if m.Auth {
		s.Auth = true
		secret := "TEXT"
		if m.Dialect == "mysql" {
			secret = "VARCHAR(1000)"
		}
		s.Columns = append(s.Columns,
			column{Name: "password_hash", SQL: secret, Base: "file"},
			column{Name: "roles", SQL: secret, Base: "file"},
			column{Name: "created_at", SQL: sqlType(mfield{Base: "int"}, m.Dialect), Base: "int"})
	}
	return s
}

func (c column) ident(dialect string) string { return quoteIdent(c.Name, dialect) }

func (c column) def(dialect string, withDefault bool) string {
	s := c.ident(dialect) + " " + c.SQL
	if c.Nullable {
		return s
	}
	s += " NOT NULL"
	if withDefault || c.Base == "file" {
		s += " DEFAULT " + zeroDefault(c, dialect)
	}
	return s
}

// zeroDefault fills a NOT NULL column added to a table with rows.
func zeroDefault(c column, dialect string) string {
	switch c.Base {
	case "string", "file":
		return "''"
	case "text":
		if dialect == "mysql" {
			return "('')"
		}
		return "''"
	case "int", "float":
		return "0"
	case "bool":
		return "FALSE"
	case "time":
		return "'1970-01-01 00:00:00'"
	}
	return "'1970-01-01'"
}

func indexName(table string, c column) string {
	if c.Unique {
		return table + "_" + c.Name + "_unique"
	}
	return table + "_" + c.Name + "_index"
}

func createIndex(table string, c column, dialect string) string {
	kind := "INDEX"
	if c.Unique {
		kind = "UNIQUE INDEX"
	}
	return "CREATE " + kind + " " + indexName(table, c) + " ON " + table + " (" + c.ident(dialect) + ");\n"
}

func dropIndex(table string, c column, dialect string) string {
	if dialect == "mysql" {
		return "DROP INDEX " + indexName(table, c) + " ON " + table + ";\n"
	}
	return "DROP INDEX " + indexName(table, c) + ";\n"
}

func idSQL(dialect string) string {
	return map[string]string{
		"postgres": "id BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY",
		"sqlite":   "id INTEGER PRIMARY KEY",
		"mysql":    "id BIGINT AUTO_INCREMENT PRIMARY KEY",
	}[dialect]
}

// migration is the SQL from old to s, up and down, and a name; old nil is the
// table's creation. A change that loses data or a column's type is refused
// unless drop says it is meant; a type change is always the user's to write.
func migration(old *schemaSnapshot, s schemaSnapshot, drop bool) (name, up, down string, err error) {
	d, t := s.Dialect, s.Table
	if old == nil {
		var b strings.Builder
		b.WriteString("CREATE TABLE " + t + " (\n    " + idSQL(d))
		for _, c := range s.Columns {
			b.WriteString(",\n    " + c.def(d, s.Auth && !c.Unique && !c.Nullable))
		}
		b.WriteString("\n);\n")
		for _, c := range s.Columns {
			if c.Unique || c.Index {
				b.WriteString(createIndex(t, c, d))
			}
		}
		return "create_" + t, b.String(), "DROP TABLE " + t + ";\n", nil
	}
	if old.Table != t || old.Dialect != d {
		return "", "", "", fmt.Errorf("the table was %s on %s: a model does not move tables or dialects", old.Table, old.Dialect)
	}
	was := map[string]column{}
	for _, c := range old.Columns {
		was[c.Name] = c
	}
	var ups, downs []string
	var changes []string
	for _, c := range s.Columns {
		o, existed := was[c.Name]
		delete(was, c.Name)
		if !existed {
			u := "ALTER TABLE " + t + " ADD COLUMN " + c.def(d, true) + ";\n"
			dn := "ALTER TABLE " + t + " DROP COLUMN " + c.ident(d) + ";\n"
			if c.Unique || c.Index {
				u += createIndex(t, c, d)
				dn = dropIndex(t, c, d) + dn
			}
			ups, downs = append(ups, u), append(downs, dn)
			changes = append(changes, "add_"+c.Name)
			continue
		}
		if o.SQL != c.SQL || o.Nullable != c.Nullable || o.Base != c.Base {
			if d == "mysql" && o.Base == "string" && c.Base == "string" && o.Nullable == c.Nullable {
				ups = append(ups, "ALTER TABLE "+t+" MODIFY COLUMN "+c.def(d, false)+";\n")
				downs = append(downs, "ALTER TABLE "+t+" MODIFY COLUMN "+o.def(d, false)+";\n")
				changes = append(changes, "resize_"+c.Name)
			} else {
				return "", "", "", fmt.Errorf("%s.%s changes type (%s → %s): write that migration yourself (gesso migrate new), then gesso gen -no-migration", t, c.Name, describe(o), describe(c))
			}
		}
		if o.Unique != c.Unique || o.Index != c.Index {
			if o.Unique || o.Index {
				ups = append(ups, dropIndex(t, o, d))
				downs = append(downs, createIndex(t, o, d))
			}
			if c.Unique || c.Index {
				ups = append(ups, createIndex(t, c, d))
				downs = append(downs, dropIndex(t, c, d))
			}
			changes = append(changes, "index_"+c.Name)
		}
	}
	for _, o := range old.Columns {
		if _, gone := was[o.Name]; !gone {
			continue
		}
		if !drop {
			return "", "", "", fmt.Errorf("%s.%s is gone from the model: dropping it loses its data — gesso gen -drop if that is meant (a rename is a new field and a migration of your own)", t, o.Name)
		}
		u := "ALTER TABLE " + t + " DROP COLUMN " + o.ident(d) + ";\n"
		dn := "ALTER TABLE " + t + " ADD COLUMN " + o.def(d, true) + ";\n"
		if o.Unique || o.Index {
			u = dropIndex(t, o, d) + u
			dn += createIndex(t, o, d)
		}
		ups, downs = append(ups, u), append(downs, dn)
		changes = append(changes, "drop_"+o.Name)
	}
	if len(ups) == 0 {
		return "", "", "", nil
	}
	slices.Reverse(downs)
	name = t + "_" + strings.Join(changes, "_")
	if len(name) > 60 {
		name = "alter_" + t
	}
	return name, strings.Join(ups, ""), strings.Join(downs, ""), nil
}

func describe(c column) string {
	if c.Nullable {
		return c.SQL + " NULL"
	}
	return c.SQL
}

// constraints maps each unique index's name, as the dialect's error names it,
// to the field's JSON name.
func (m model) Constraints() map[string]string {
	out := map[string]string{}
	for _, c := range m.snapshot().Columns {
		if !c.Unique {
			continue
		}
		json := lowerCamel(c.Name)
		switch m.Dialect {
		case "sqlite":
			out[m.Table+"."+c.Name] = json
		case "mysql":
			out[m.Table+"."+indexName(m.Table, c)] = json
		default:
			out[indexName(m.Table, c)] = json
		}
	}
	return out
}

// ConstraintEntries are Constraints, sorted, for the template.
func (m model) ConstraintEntries() [][2]string {
	var out [][2]string
	for k, v := range m.Constraints() {
		out = append(out, [2]string{k, v})
	}
	slices.SortFunc(out, func(a, b [2]string) int { return strings.Compare(a[0], b[0]) })
	return out
}

// findHooks reads which of gen's hooks the module's own files define on
// *Module: BeforeCreate, BeforeUpdate, BeforeDelete, and routes for routes of
// its own.
func findHooks(moduleDir string) (hooks, error) {
	var h hooks
	entries, err := os.ReadDir(moduleDir)
	if err != nil {
		return h, err
	}
	fset := gotoken.NewFileSet()
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, ".gen.go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		f, err := parser.ParseFile(fset, filepath.Join(moduleDir, name), nil, parser.SkipObjectResolution)
		if err != nil {
			return h, err
		}
		for _, d := range f.Decls {
			fn, ok := d.(*ast.FuncDecl)
			if !ok || fn.Recv == nil || len(fn.Recv.List) != 1 {
				continue
			}
			star, ok := fn.Recv.List[0].Type.(*ast.StarExpr)
			if !ok || !isName(star.X, "Module") {
				continue
			}
			switch fn.Name.Name {
			case "BeforeCreate":
				h.BeforeCreate = true
			case "BeforeUpdate":
				h.BeforeUpdate = true
			case "BeforeDelete":
				h.BeforeDelete = true
			case "routes":
				h.Routes = true
			default:
				if field, ok := strings.CutPrefix(fn.Name.Name, "Process"); ok && field != "" {
					if h.Process == nil {
						h.Process = map[string]bool{}
					}
					h.Process[field] = true
				}
			}
		}
	}
	return h, nil
}

type genOutput struct {
	path string
	src  []byte
}

// renderModel is the generated files of the model in modelsDir.
func renderModel(m *model, modelsDir string) ([]genOutput, error) {
	var out []genOutput
	for _, f := range []struct{ tmpl, path string }{
		{"requests.gen.go.tmpl", filepath.Join(modelsDir, "requests.gen.go")},
		{"responses.gen.go.tmpl", filepath.Join(modelsDir, "responses.gen.go")},
		{"repository.gen.go.tmpl", filepath.Join(filepath.Dir(modelsDir), "repository.gen.go")},
		{"module.gen.go.tmpl", filepath.Join(filepath.Dir(modelsDir), "module.gen.go")},
	} {
		var buf bytes.Buffer
		buf.WriteString(modelHeader)
		if err := genTemplates.ExecuteTemplate(&buf, f.tmpl, m); err != nil {
			return nil, err
		}
		src, err := format.Source(buf.Bytes())
		if err != nil {
			return nil, fmt.Errorf("%s: %w\n%s", f.path, err, buf.String())
		}
		out = append(out, genOutput{f.path, src})
	}
	return out, nil
}

// genModel brings the module whose models folder is modelsDir up to date: its
// generated files, and a migration for what changed. dialect names the SQL for
// a model gen has not seen before; after, the snapshot says it.
type genModelOptions struct {
	root        string // where migration versions are unique: the project
	dialect     string
	check       bool // report, write nothing
	drop        bool // a column gone from the model may be dropped
	noMigration bool // the user wrote the migration: only update the snapshot
	now         func() time.Time
}

// genModel returns the paths it wrote, or, with check, the ones that are stale.
func genModel(modelsDir string, o genModelOptions) ([]string, error) {
	m, err := parseModel(modelsDir)
	if err != nil {
		return nil, err
	}
	snapPath := filepath.Join(modelsDir, "schema.gen.json")
	var old *schemaSnapshot
	if b, err := os.ReadFile(snapPath); err == nil {
		old = &schemaSnapshot{}
		if err := json.Unmarshal(b, old); err != nil {
			return nil, fmt.Errorf("%s: %w", snapPath, err)
		}
		m.Dialect = old.Dialect
	} else {
		m.Dialect = o.dialect
	}
	if m.Dialect == "" {
		return nil, fmt.Errorf("%s: no schema.gen.json, and no dialect to start one in", modelsDir)
	}
	for i := range m.Fields {
		m.Fields[i].Ident = quoteIdent(m.Fields[i].Column, m.Dialect)
	}
	mod, err := readModule(o.root)
	if err != nil {
		return nil, err
	}
	abs, _ := filepath.Abs(modelsDir)
	root, _ := filepath.Abs(o.root)
	rel, err := filepath.Rel(root, abs)
	if err != nil || strings.HasPrefix(rel, "..") {
		return nil, fmt.Errorf("%s is outside the project %s", modelsDir, o.root)
	}
	m.Models = mod + "/" + filepath.ToSlash(rel)
	if len(m.guardFiles) > 0 {
		guardsDir := filepath.Join(filepath.Dir(filepath.Dir(modelsDir)), "guards")
		for _, g := range m.guardFiles {
			if _, err := os.Stat(filepath.Join(guardsDir, g+".go")); err != nil {
				return nil, fmt.Errorf("%s names the guard %s, and there is no %s: gesso add guard %s", modelsDir, g, filepath.Join(guardsDir, g+".go"), g)
			}
		}
		m.Guards = mod + "/" + filepath.ToSlash(filepath.Dir(filepath.Dir(rel))) + "/guards"
	}
	if m.Hooks, err = findHooks(filepath.Dir(modelsDir)); err != nil {
		return nil, err
	}
	m.buildSQL()
	files, err := renderModel(m, modelsDir)
	if err != nil {
		return nil, err
	}
	snap, err := json.MarshalIndent(m.snapshot(), "", "  ")
	if err != nil {
		return nil, err
	}
	files = append(files, genOutput{snapPath, append(snap, '\n')})
	name, up, down, err := migration(old, m.snapshot(), o.drop)
	if err != nil {
		return nil, err
	}
	var touched []string
	for _, f := range files {
		if cur, err := os.ReadFile(f.path); err == nil && bytes.Equal(cur, f.src) {
			continue
		}
		touched = append(touched, f.path)
		if !o.check {
			if err := os.WriteFile(f.path, f.src, 0o644); err != nil {
				return touched, err
			}
		}
	}
	if up != "" && !o.noMigration {
		migDir := filepath.Join(filepath.Dir(modelsDir), "migrations")
		if o.check {
			return append(touched, filepath.Join(migDir, "…_"+name+".up.sql")), nil
		}
		paths, err := writeMigration(o.root, migDir, name, up, down, o.now)
		touched = append(touched, paths...)
		if err != nil {
			return touched, err
		}
	}
	return touched, nil
}
