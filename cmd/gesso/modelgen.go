var genTemplates = template.Must(template.New("").Funcs(template.FuncMap{
	"ph": func(dialect string, n int) string {
		if dialect == "postgres" {
			return "$" + strconv.Itoa(n)
		}
		return "?"
	},
	"add": func(a, b int) int { return a + b },
	"lit": func(sql string) string { return strings.ReplaceAll(sql, `"`, `\"`) },
}).ParseFS(scaffoldFS, "scaffold/gen/*.tmpl"))

var (
	tableDirective = regexp.MustCompile(`^//gesso:table\s+([a-z][a-z0-9_]*)\s*$`)
	modelDirective = regexp.MustCompile(`^//gesso:(sortable|auth|write|read)(?:\s+([a-z][A-Za-z0-9]*))?\s*$`)
)

type model struct {
	Pkg      string // docs: the module's package
	Models   string // the import path of its models package
	Entity   string // Doc
	Plural   string // Docs
	Table    string // docs
	Dialect  string
	Fields   []mfield
	Key      *mfield // nil: the id
	Sort     *mfield // nil: by id, or by position when Sortable
	UsesTime bool
	UsesDate bool

	Sortable    bool   // //gesso:sortable: kept in an order of the client's, a position column
	Auth        bool   // //gesso:auth: the users who sign in
	Write, Read string // the guards' Go names, from //gesso:write and //gesso:read
	Gate        *mfield
	Guarded     []string // the field guards' Go names, each once
	Guards      string   // the import path of the guards package
	Listable    bool     // some field is listable: the list answers ResXItem
	Hooks       hooks
	SQL         modelSQL
	guardFiles  []string // the guards it names, as their files are named
}

// hooks are the user's methods on *Module that gen calls.
type hooks struct {
	BeforeCreate, BeforeUpdate, BeforeDelete, Routes bool
	Process                                          map[string]bool // Process<Field>, by the field's Go name
}

// ProcessOf reports whether the user's code processes the file field named go.
func (h hooks) ProcessOf(goName string) bool { return h.Process[goName] }

type mfield struct {
	Go, JSON, Column, Ident string
	Type                    string // the Go type: string, int64, *date.Date
	Base                    string // string, text, int, bool, float, time, date
	Nullable                bool   // a pointer: the column takes NULL
	Unique, Index           bool
	Key, Sort, Optional     bool
	Listable, Filterable    bool
	Orderable               bool
	Default                 string   // default=: a literal, @today, @now or @user
	File                    string   // file or image: a column that holds a stored file's key
	Accept                  []string // the file's types: image/png …
	MaxSize                 string   // the file's largest, as written: 5MiB
	MaxBytes                int64
	Width, Height           int    // an image's fit=WxH or fill=WxH
	Fill                    bool   // fill: cropped to exactly Width × Height
	Format                  string // an image's jpeg or png; "" keeps PNG and GIF as PNG
	Quality                 int
	Transforms              []string // trim, lower, upper, collapse, slugify, in order
	Self                    bool     // a signed-in user may change it on themselves: PATCH /auth/me
	Public                  bool     // a file anyone may fetch, past the model's read guard
	Routes                  bool     // a file with PUT and DELETE routes of its own, beside the record's
	Guard                   string   // the Go name of the guard that may see and write it
	GateGuard               string   // a gate: records with it false are the guard's only
	Rules                   []string // validation rules beyond what the options imply
	Rule                    string   // the validate tag on create and update
	Patch                   string   // the validate tag on a PATCH
}

// ResType is the field's type in a response: a pointer, left out, when a
// guard hides it.
func (f mfield) ResType() string {
	if f.File != "" {
		return "*string" // its URL
	}
	if f.Guard != "" && !f.Nullable {
		return "*" + f.Type
	}
	return f.Type
}

// checkDefault refuses a default the field cannot hold.
func (f mfield) checkDefault() error {
	v := f.Default
	switch {
	case f.Key || f.Unique:
		return errors.New("a key or a unique field has no default: two records would share it")
	case v == "@today" && f.Base != "date", v == "@now" && f.Base != "time", v == "@user" && f.Base != "string" && f.Base != "text":
		return fmt.Errorf("default=%s is for a %s", v, map[string]string{"@today": "date", "@now": "time", "@user": "string"}[v])
	case strings.HasPrefix(v, "@") && v != "@today" && v != "@now" && v != "@user":
		return fmt.Errorf("unknown default %s: @today, @now, @user, or a value", v)
	case strings.HasPrefix(v, "@"):
		return nil
	}
	var err error
	switch f.Base {
	case "int":
		_, err = strconv.ParseInt(v, 10, 64)
	case "float":
		_, err = strconv.ParseFloat(v, 64)
	case "bool":
		_, err = strconv.ParseBool(v)
	case "time", "date":
		err = fmt.Errorf("a %s's default is @%s", f.Base, map[string]string{"time": "now", "date": "today"}[f.Base])
	}
	if err != nil {
		return fmt.Errorf("default=%s: %w", v, err)
	}
	for _, r := range f.Rules {
		if words, ok := strings.CutPrefix(r, "oneof="); ok && !slices.Contains(strings.Fields(words), v) {
			return fmt.Errorf("default=%s is not one of %s", v, words)
		}
	}
	return nil
}

// DefaultValue is the default as Go: a literal, or what the generated code
// computes for @today, @now and @user.
func (f mfield) DefaultValue() string {
	switch f.Default {
	case "@today":
		return "date.Today(time.Now(), time.Local)"
	case "@now":
		return "time.Now()"
	case "@user":
		return "id.Name"
	}
	if f.Base == "string" || f.Base == "text" {
		return strconv.Quote(f.Default)
	}
	return f.Default
}

// ReqType is the field's type in a create or update: an Optional when a guard
// may refuse it, or a default fills it, to tell sent from left out.
func (f mfield) ReqType() string {
	if f.Guard != "" || f.Default != "" {
		return "gesso.Optional[" + f.Type + "]"
	}
	return f.Type
}

// ReqTag is the field's json and validate tags in a create or update.
func (f mfield) ReqTag() string {
	if f.Guard != "" || f.Default != "" {
		t := `json:"` + f.JSON + `,omitzero" form:"` + f.JSON + `"`
		if f.Patch != "" {
			t += ` validate:"` + f.Patch + `"`
		}
		return t
	}
	t := `json:"` + f.JSON + `" form:"` + f.JSON + `"`
	if f.Rule != "" {
		t += ` validate:"` + f.Rule + `"`
	}
	return t
}

