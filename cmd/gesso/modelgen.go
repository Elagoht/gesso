// A module's model — the struct in models/models.go marked //gesso:table — is
// the one source of the module: gesso gen writes module.gen.go (the module, its
// routes and handlers), repository.gen.go, models/requests.gen.go and
// models/responses.gen.go from it, and a migration for whatever changed since
// models/schema.gen.json. What the user writes beside them — hooks, routes of
// their own — gen finds by name and calls.

